first_number = int(input("Введіть перше число: "))
second_number = int(input("Введіть друге число: "))
third_number = int(input("Введіть третє число: "))

numbers_sum = first_number + second_number + third_number
print(f"Сума чисел: {numbers_sum}")

numbers_product = first_number * second_number * third_number
print(f"Добуток чисел: {numbers_product}")

numbers_average = numbers_sum / 3
print(f"Середнє арифметичне: {numbers_average}")
